// Builds dist/ (JSON, minified JSON, CSV, per-category JSON), docs/index.html (GitHub Pages
// explorer) and the formula table in README.md. Refuses to build if validation fails.
// Usage: node scripts/build.mjs
import { writeFileSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { ROOT, CATEGORIES, loadFormulas, validateAll, stripInternal } from "./lib.mjs";
import { VERSION, REPO_URL, PAGES_URL, CDN_URL } from "./config.mjs";

const formulas = loadFormulas();
const problems = validateAll(formulas);
if (problems.length) {
  console.error("Validation failed — run `npm run validate` for details.");
  process.exit(1);
}

const clean = formulas.map(stripInternal).sort((a, b) =>
  a.category.localeCompare(b.category) || a.topic.localeCompare(b.topic) || a.name.localeCompare(b.name));

const meta = {
  name: "Math Formulas Dataset",
  version: VERSION,
  description: "Machine-readable math formulas with LaTeX, variables, computable expressions and verified worked examples.",
  source: "https://mathovia.com/",
  repository: REPO_URL,
  license: "CC-BY-4.0",
  attribution: "Formula data from Mathovia (https://mathovia.com)",
  count: clean.length,
};

// ---- dist ------------------------------------------------------------------
const DIST = join(ROOT, "dist");
rmSync(DIST, { recursive: true, force: true });
mkdirSync(join(DIST, "categories"), { recursive: true });

writeFileSync(join(DIST, "formulas.json"), JSON.stringify({ meta, formulas: clean }, null, 2) + "\n");
writeFileSync(join(DIST, "formulas.min.json"), JSON.stringify({ meta, formulas: clean }));

for (const cat of CATEGORIES) {
  const items = clean.filter((f) => f.category === cat);
  if (!items.length) continue;
  writeFileSync(join(DIST, "categories", `${cat}.json`),
    JSON.stringify({ meta: { ...meta, category: cat, count: items.length }, formulas: items }, null, 2) + "\n");
}

const csvCell = (v) => {
  const s = v === undefined || v === null ? "" : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
const csvCols = ["id", "name", "category", "topic", "latex", "plain", "description", "variables", "compute", "conditions", "tags", "learn_url", "calculate_url", "practice_url"];
const csvRows = clean.map((f) => [
  f.id, f.name, f.category, f.topic, f.latex, f.plain, f.description,
  f.variables.map((v) => `${v.key}=${v.name}`).join("; "),
  f.compute, (f.conditions || []).join("; "), f.tags.join("; "),
  f.links.learn, f.links.calculate, f.links.practice,
].map(csvCell).join(","));
writeFileSync(join(DIST, "formulas.csv"), "\uFEFF" + [csvCols.join(","), ...csvRows].join("\n") + "\n");

// ---- README table ----------------------------------------------------------
const primaryLink = (f) => f.links.learn || f.links.calculate || f.links.practice;
const titleCase = (s) => s.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()).replace(/ (Of|And|The|Vs) /g, (m) => m.toLowerCase());
let table = "";
for (const cat of CATEGORIES) {
  const items = clean.filter((f) => f.category === cat);
  if (!items.length) continue;
  table += `\n### ${titleCase(cat)} (${items.length})\n\n| Formula | Expression | Learn more |\n|---|---|---|\n`;
  for (const f of items) {
    const links = [
      f.links.learn && `[Lesson](${f.links.learn})`,
      f.links.calculate && `[Calculator](${f.links.calculate})`,
      f.links.practice && `[Practice](${f.links.practice})`,
    ].filter(Boolean).join(" · ");
    table += `| [${f.name}](${PAGES_URL}#${f.id}) | \`${f.plain.replace(/\|/g, "\\|")}\` | ${links} |\n`;
  }
}
const readmePath = join(ROOT, "README.md");
const readme = readFileSync(readmePath, "utf8");
const START = "<!-- FORMULAS:START -->", END = "<!-- FORMULAS:END -->";
if (!readme.includes(START) || !readme.includes(END)) {
  console.error("README.md is missing the FORMULAS:START/END markers.");
  process.exit(1);
}
const before = readme.slice(0, readme.indexOf(START) + START.length);
const after = readme.slice(readme.indexOf(END));
writeFileSync(readmePath, `${before}\n<!-- Generated by scripts/build.mjs — do not edit by hand. -->\n${table}\n${after}`
  .replace(/\*\*\d+ formulas\*\*/, `**${clean.length} formulas**`));

// ---- docs/index.html (GitHub Pages) ---------------------------------------
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const fmt = (v) => Array.isArray(v) ? `[${v.join(", ")}]` : String(v);

const cards = clean.map((f) => {
  const vars = f.variables.map((v) => `<li><span class="tex">\\(${esc(v.symbol)}\\)</span> ${esc(v.name)}</li>`).join("");
  const conds = (f.conditions || []).length
    ? `<p class="conds"><strong>Conditions:</strong> ${f.conditions.map(esc).join("; ")}</p>` : "";
  const ex = f.examples[0];
  const exInputs = Object.entries(ex.inputs).map(([k, v]) => `${esc(k)} = ${esc(v)}`).join(", ");
  const exOut = ex.display ? `${esc(ex.display)} (${esc(fmt(ex.output))})` : esc(fmt(ex.output));
  const links = [
    f.links.learn && `<a href="${f.links.learn}">${esc(f.name)} lesson</a>`,
    f.links.calculate && `<a href="${f.links.calculate}">Calculator</a>`,
    f.links.practice && `<a href="${f.links.practice}">Practice problems</a>`,
  ].filter(Boolean).join("");
  return `<article id="${f.id}" class="card" data-cat="${f.category}" data-search="${esc((f.name + " " + f.topic + " " + f.tags.join(" ")).toLowerCase())}">
  <header><h3><a href="#${f.id}">${esc(f.name)}</a></h3><span class="badge">${esc(titleCase(f.topic))}</span></header>
  <div class="formula">\\[${esc(f.latex)}\\]</div>
  <p>${esc(f.description)}</p>
  <details><summary>Variables &amp; example</summary>
    <ul class="vars">${vars}</ul>${conds}
    <p class="ex"><strong>Example:</strong> ${exInputs} → <strong>${exOut}</strong>${ex.note ? ` — ${esc(ex.note)}` : ""}</p>
    <p class="code"><code>${esc(f.compute)}</code></p>
  </details>
  <nav class="links">${links}</nav>
</article>`;
}).join("\n");

const catButtons = CATEGORIES.filter((c) => clean.some((f) => f.category === c))
  .map((c) => `<button data-filter="${c}">${titleCase(c)} (${clean.filter((f) => f.category === c).length})</button>`).join("");

